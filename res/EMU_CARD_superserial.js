// Discovery container. Apple2IO mounts a separate live instance.
if(oEMU===undefined) var oEMU = {"component":{"IO":{"SuperSerial":new SuperSerialCard()}}}
else oEMU.component.IO.SuperSerial = new SuperSerialCard();


function SuperSerialCard()
{
    const bDebug = true;

    this.id = {"PCODE":"SSC", "icon":"fa fa-terminal"};

    /*
     * DIP values are the values observed by the SSC firmware.
     * The default is a conventional communications configuration:
     * 9600 baud, 8 data bits, no parity, one stop bit, no automatic LF.
     *
     * Modem booleans are logical states: true means the signal is asserted.
     */
    var state =
    {
         "active":true
        ,"dip1":0xE0
        ,"dip2":0x0A

        ,"command":0x00
        ,"control":0x00

        ,"rx_data":0x00
        ,"rx_full":false
        ,"rx_errors":0x00

        ,"irq":false
        ,"modem":{"cts":true,"dsr":true,"dcd":true}

        ,"rx_count":0
        ,"tx_count":0
    };

    // Keep state visible in the same way as the other peripheral containers.
    this.state = state;

    var ssc = this;       // stand-in where 'this' is absent inside callbacks

    var rxQueue = [];
    var txQueue = [];
    var transmitHandler = null;

    this.action =
    {
        "SlotIO":
        {
            "RD":{"callback":function(addr,ctx) {
                return ssc.read(addr,ctx);
            }},
            "WR":{"callback":function(addr,d8,ctx) {
                return ssc.write(addr,d8,ctx);
            }}
        },
        "SlotROM":
        {
            "RD":{"callback":function(addr,ctx) {
                return ssc.readROM(addr,ctx);
            }}
        },
        "HostROM":
        {
            "RD":{"callback":function(addr,ctx) {
                return ssc.readHostROM(addr,ctx);
            }}
        }
    };


    // Relative SlotIO addresses: $C08n-$C08F, with n supplied by the slot.
    const DIPSW1       = 0x01;
    const DIPSW2       = 0x02;
    const ACIA_DATA    = 0x08;
    const ACIA_STATUS  = 0x09;
    const ACIA_COMMAND = 0x0A;
    const ACIA_CONTROL = 0x0B;


    function mountedHw()
    {
        if(typeof(apple2plus)!="object" || !apple2plus || typeof(apple2plus.hwObj)!="function")
            return null;
        return apple2plus.hwObj();
    }


    function receiverIRQEnabled()
    {
        // 6551 command register:
        // bit 0 = DTR (1 = ready), bit 1 = receiver IRQ disable.
        return (state.command & 0x01)!==0 && (state.command & 0x02)===0;
    }


    function updateIRQ(asserted)
    {
        state.irq = !!asserted;

        var hw = mountedHw();
        if(!hw) return;

        /*
         * RetroAppleJS currently exposes the 6502 IRQ input as one hardware
         * line. The SSC therefore drives that existing line directly rather
         * than adding an SSC-specific IRQ API to Apple2Hw.
         */
        hw.irq_signal = state.irq ? 1 : 0;
    }


    function primeReceiver()
    {
        if(state.rx_full || rxQueue.length===0) return;

        state.rx_data = rxQueue.shift() & 0xFF;
        state.rx_full = true;
        state.rx_count++;

        if(receiverIRQEnabled()) updateIRQ(true);
    }


    function statusByte()
    {
        var d8 = 0x10;                    // bit 4: TDRE, untimed transmitter ready

        if(state.irq)        d8 |= 0x80;
        if(!state.modem.dsr) d8 |= 0x40;  // DSRB high = not ready
        if(!state.modem.dcd) d8 |= 0x20;  // DCDB high = no carrier
        if(state.rx_full)    d8 |= 0x08;

        d8 |= state.rx_errors & 0x07;
        return d8 & 0xFF;
    }


    function readData()
    {
        var d8 = state.rx_data & 0xFF;

        if(state.rx_full)
        {
            state.rx_full = false;
            state.rx_errors = 0x00;
            updateIRQ(false);

            // Load the next host byte only after the emulated 6551 RDR was read.
            primeReceiver();
        }

        return d8;
    }


    function readStatus()
    {
        var d8 = statusByte();

        // 6551 status-register read clears the IRQ indication/latch.
        if(state.irq) updateIRQ(false);

        return d8;
    }


    function programmedReset()
    {
        /*
         * 6551 programmed reset (write to the status-register address):
         * clear command bits 4..0, preserve command bits 7..5 and Control.
         */
        state.command &= 0xE0;
        state.rx_errors &= 0x03;   // overrun (bit 2) is cleared by programmed reset
        updateIRQ(false);
    }


    function ownsExpansionROM()
    {
        if(!ssc.mount) return false;
        return oEMU.component.IO.ACTION_MAP.Hslot == (ssc.mount.slotN-1);
    }


    function selectExpansionROM(ctx)
    {
        // Safe/debugger ROM inspection must not change C8 ownership.
        if(ctx && ctx.bRO===true) return false;
        if(!ssc.mount || !ssc.mount.ranges || !ssc.mount.ranges.HostROM) return false;

        var CIO = oEMU.component.IO;
        if(!CIO.ACTION_MAP) return false;

        if(CIO.ACTION_MAP.Hslot == (ssc.mount.slotN-1)) return true;

        CIO.ACTION_MAP.Hslot = ssc.mount.slotN-1;

        /*
         * Match the existing Videx-style shared C8 ownership mechanism:
         * the slot ROM access installs this card's HostROM callback until
         * $CFFF releases the expansion-ROM window or another card claims it.
         */
        var range = ssc.mount.ranges.HostROM;
        for(var i=range.from;i<=range.to;i++)
            CIO.ACTION_MAP.RD[i] = ssc.action.HostROM.RD.callback;

        if(bDebug)
            console.log("SSC claims $C800-$CFFF from PR#"+(ssc.mount.slotN-1));

        return true;
    }


    function releaseExpansionROM()
    {
        if(!ssc.mount || !oEMU.component.IO.ACTION_MAP) return false;

        var CIO = oEMU.component.IO;
        if(CIO.ACTION_MAP.Hslot != (ssc.mount.slotN-1)) return false;

        CIO.ACTION_MAP.Hslot = null;

        /*
         * The callback can remain installed: readHostROM() checks Hslot and
         * behaves as an unclaimed bus until a slot ROM selects a card again.
         * This also avoids introducing a new global HostROM manager.
         */
        return true;
    }


    this.read = function(addr,ctx)
    {
        switch(addr & 0x0F)
        {
            case DIPSW1:
                return state.dip1 & 0xFF;

            case DIPSW2:
                // SSC DIPSW2 bit 0 is the live active-low CTS input.
                return ((state.dip2 & 0xFE) | (state.modem.cts ? 0 : 1)) & 0xFF;

            case ACIA_DATA:
                return readData();

            case ACIA_STATUS:
                return readStatus();

            case ACIA_COMMAND:
                return state.command & 0xFF;

            case ACIA_CONTROL:
                return state.control & 0xFF;
        }

        return 0x00;
    };


    this.write = function(addr,d8,ctx)
    {
        d8 &= 0xFF;

        switch(addr & 0x0F)
        {
            case ACIA_DATA:
                /*
                 * First implementation is intentionally untimed: a byte moves
                 * immediately into the host-side TX queue and TDRE remains set.
                 */
                txQueue.push(d8);
                state.tx_count++;

                if(typeof(transmitHandler)=="function")
                    transmitHandler(d8,ssc);
                break;

            case ACIA_STATUS:
                programmedReset();
                break;

            case ACIA_COMMAND:
                state.command = d8;

                if(state.rx_full && receiverIRQEnabled()) updateIRQ(true);
                else if(!receiverIRQEnabled()) updateIRQ(false);
                break;

            case ACIA_CONTROL:
                state.control = d8;
                break;
        }

        return 0x00;
    };


    this.readROM = function(addr,ctx)
    {
        /*
         * 341-0065-A physical layout:
         *   $000-$6FF -> $C800-$CEFF expansion ROM
         *   $700-$7FF -> slot page $Cn00-$CnFF
         *
         * A real CPU read of the slot page selects this card's C8 ROM.
         */
        selectExpansionROM(ctx);
        return SSC_ROM[0x700 + (addr & 0xFF)];
    };


    this.readHostROM = function(addr,ctx)
    {
        /*
         * Apple2IO supplies the full C000-relative bus address in ctx.rel_addr.
         * The normal callback argument itself is only the offset within the
         * decoded 256-byte line and is therefore insufficient for a 2 KiB ROM.
         */
        var rel_addr;

        if(ctx && Number.isFinite(ctx.rel_addr))
            rel_addr = ctx.rel_addr;
        else if(ctx && Number.isFinite(ctx.line))
            rel_addr = ctx.line + (addr & 0xFF);
        else
            rel_addr = (ssc.action.HostROM.base || 0x800) + (addr & 0xFF);

        // C8 space exists electrically only while this card owns it.
        if(!ownsExpansionROM()) return 0x00;

        var d8 = SSC_ROM[(rel_addr - 0x800) & 0x07FF];

        // $CFFF releases the shared expansion-ROM window after the access.
        if((rel_addr & 0x0FFF)==0x0FFF && !(ctx && ctx.bRO===true))
            releaseExpansionROM();

        return d8;
    };


    // Host -> Apple II. Accept a byte, string, Array or Uint8Array.
    this.inject = function(data)
    {
        var count = 0;

        function enqueue(d8)
        {
            rxQueue.push(Number(d8) & 0xFF);
            count++;
        }

        if(typeof(data)=="number")
            enqueue(data);
        else if(typeof(data)=="string")
        {
            for(var i=0;i<data.length;i++) enqueue(data.charCodeAt(i));
        }
        else if(data && typeof(data.length)=="number")
        {
            for(var j=0;j<data.length;j++) enqueue(data[j]);
        }

        primeReceiver();
        return count;
    };


    // Apple II -> host.
    this.drainTx = function()
    {
        var out = new Uint8Array(txQueue);
        txQueue.length = 0;
        return out;
    };


    this.peekTx = function()
    {
        return new Uint8Array(txQueue);
    };


    this.setTransmitHandler = function(fn)
    {
        transmitHandler = typeof(fn)=="function" ? fn : null;
        return transmitHandler;
    };


    this.setModemLines = function(lines)
    {
        lines = lines || {};

        if(lines.cts!==undefined) state.modem.cts = !!lines.cts;
        if(lines.dsr!==undefined) state.modem.dsr = !!lines.dsr;
        if(lines.dcd!==undefined) state.modem.dcd = !!lines.dcd;

        return Object.assign({},state.modem);
    };


    this.setDIP = function(block,value)
    {
        value = Number(value) & 0xFF;

        if(Number(block)===1) state.dip1 = value;
        if(Number(block)===2) state.dip2 = value;

        return Number(block)===1 ? state.dip1 : state.dip2;
    };


    this.getBaudRate = function()
    {
        // 6551 internal-clock baud table selected by Control bits 3..0.
        var baud = [0,50,75,109.92,134.58,150,300,600,1200,1800,2400,3600,4800,7200,9600,19200];
        return baud[state.control & 0x0F] || 0;
    };


    this.getRegisters = function()
    {
        return {
             "status":statusByte()
            ,"command":state.command & 0xFF
            ,"control":state.control & 0xFF
            ,"baud":ssc.getBaudRate()
            ,"rxQueued":rxQueue.length + (state.rx_full ? 1 : 0)
            ,"txQueued":txQueue.length
        };
    };


    this.reset = function()
    {
        rxQueue.length = 0;
        txQueue.length = 0;

        state.command = 0x00;
        state.control = 0x00;
        state.rx_data = 0x00;
        state.rx_full = false;
        state.rx_errors = 0x00;
        state.rx_count = 0;
        state.tx_count = 0;

        updateIRQ(false);
        releaseExpansionROM();
    };


    this.restart = function()
    {
        ssc.reset();
    };
}
