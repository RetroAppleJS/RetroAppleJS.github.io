function ThunderClockPlusCard()
{
    const bDebug = false;

    this.id = {"PCODE":"TCLKP", "icon":"fa fa-clock"};

    var state =
    {
         "active":true
    };

    this.state = state;

    var thunderclock = this;       // stand-in where 'this' is absent inside callbacks


    /*
     * NEC uPD1990AC command values.
     *
     * The physical ThunderClock drives the chip's three parallel command pins
     * from bits 3..5 of its output latch.  Command 7 is TEST on the uPD1990A.
     */
    const RTC_REGISTER_HOLD = 0;
    const RTC_SHIFT         = 1;
    const RTC_TIME_SET      = 2;
    const RTC_TIME_READ     = 3;
    const RTC_TP_64HZ       = 4;
    const RTC_TP_256HZ      = 5;
    const RTC_TP_2048HZ     = 6;
    const RTC_TEST          = 7;


    /*
     * Browser-backed uPD1990A.
     *
     * The real chip has a five-byte (40-bit) serial register:
     *   byte 0  BCD seconds
     *   byte 1  BCD minutes
     *   byte 2  BCD hours
     *   byte 3  BCD day-of-month
     *   byte 4  high nibble = month (1..12)
     *           low nibble  = day-of-week (0=Sunday .. 6=Saturday)
     *
     * The chip does not contain a year register.  JavaScript still needs a
     * year internally to make calendar rollover behave naturally; software
     * never sees it through the ThunderClock hardware interface.
     *
     * baseTimeMs/hostBaseMs use the same "emulated time + host elapsed time"
     * model as the Serial Pro RTC.  The clock object survives reset()/restart()
     * while the mounted card instance remains alive.
     */
    var rtcStartMs = Date.now();
    var rtc =
    {
         "baseTimeMs":rtcStartMs
        ,"hostBaseMs":rtcStartMs
        ,"running":true
        ,"weekdayOffset":0
        ,"shift":new Uint8Array(5)
        ,"mode":RTC_REGISTER_HOLD
        ,"commandPending":RTC_REGISTER_HOLD
        ,"control":0x00
        ,"dataIn":0
        ,"dataOut":0
        ,"clk":0
        ,"stb":0
        ,"testMode":false
        ,"tpRate":64
    };


    function rtcToBCD(value)
    {
        value = Math.max(0,Math.floor(value));
        return (((Math.floor(value/10) % 10) << 4) | (value % 10)) & 0xFF;
    }


    function rtcFromBCD(value)
    {
        return ((((value >> 4) & 0x0F) * 10) + (value & 0x0F)) & 0xFF;
    }


    function rtcCurrentDate()
    {
        var ms = rtc.baseTimeMs;

        if(rtc.running)
            ms += Date.now() - rtc.hostBaseMs;

        return new Date(ms);
    }


    function rtcRebase(date)
    {
        rtc.baseTimeMs = date.getTime();
        rtc.hostBaseMs = Date.now();
    }


    function rtcSetRunning(running)
    {
        running = !!running;

        if(rtc.running==running)
            return;

        // Freeze the exact current value when stopping.  When starting again,
        // elapsed wall time begins from that frozen value rather than including
        // the period for which the uPD1990 counter was stopped.
        if(!running)
            rtcRebase(rtcCurrentDate());
        else
            rtc.hostBaseMs = Date.now();

        rtc.running = running;
    }


    function rtcPackTime()
    {
        var date = rtcCurrentDate();

        rtc.shift[0] = rtcToBCD(date.getSeconds());
        rtc.shift[1] = rtcToBCD(date.getMinutes());
        rtc.shift[2] = rtcToBCD(date.getHours());
        rtc.shift[3] = rtcToBCD(date.getDate());

        var dow = (date.getDay() + rtc.weekdayOffset) % 7;
        rtc.shift[4] = (((date.getMonth()+1) & 0x0F) << 4) | (dow & 0x0F);
    }


    function rtcApplyShiftToClock()
    {
        var current = rtcCurrentDate();

        var second = Math.max(0,Math.min(59,rtcFromBCD(rtc.shift[0])));
        var minute = Math.max(0,Math.min(59,rtcFromBCD(rtc.shift[1])));
        var hour   = Math.max(0,Math.min(23,rtcFromBCD(rtc.shift[2])));
        var day    = Math.max(1,Math.min(31,rtcFromBCD(rtc.shift[3])));
        var month  = Math.max(1,Math.min(12,(rtc.shift[4] >> 4) & 0x0F));
        var dow    = rtc.shift[4] & 0x0F;
        if(dow>6) dow %= 7;

        /*
         * Preserve the current internal year because a real uPD1990A has no
         * year field.  Build month/day from day 1 first so JavaScript does not
         * accidentally carry a large existing day into the following month.
         */
        var date = new Date(current.getTime());
        var year = date.getFullYear();

        date.setFullYear(year,month-1,1);
        date.setHours(hour,minute,second,0);
        date.setDate(day);

        rtcRebase(date);
        rtc.weekdayOffset = (dow - date.getDay() + 7) % 7;
    }


    function rtcShiftClockRising()
    {
        if(rtc.mode!=RTC_SHIFT)
            return;

        /*
         * uPD1990A shifts toward bit 0.  DATA IN enters bit 7 of the final
         * byte; DATA OUT becomes the new bit 0 of byte 0 after the edge.
         */
        var incoming = rtc.dataIn & 1;

        for(var i=0;i<rtc.shift.length;i++)
        {
            var next = i+1<rtc.shift.length ? (rtc.shift[i+1] & 1) : incoming;
            rtc.shift[i] = ((rtc.shift[i] >> 1) | (next << 7)) & 0xFF;
        }

        rtc.dataOut = rtc.shift[0] & 1;
    }


    function rtcLatchCommand(command)
    {
        command &= 0x07;
        rtc.mode = command;

        /*
         * This follows the uPD1990A behavior used by the ThunderClock ROM and
         * by MAME's uPD1990A device model.
         */
        if(command==RTC_REGISTER_HOLD ||
           command==RTC_TP_64HZ ||
           command==RTC_TP_256HZ ||
           command==RTC_TP_2048HZ)
        {
            rtcSetRunning(true);
            rtc.testMode = false;
        }

        switch(command)
        {
            case RTC_REGISTER_HOLD:
                rtc.tpRate = 64;
                break;

            case RTC_SHIFT:
                if(!rtc.testMode)
                    rtcSetRunning(true);
                rtc.dataOut = rtc.shift[0] & 1;
                break;

            case RTC_TIME_SET:
                rtcSetRunning(false);
                rtc.dataOut = rtc.shift[0] & 1;
                rtcApplyShiftToClock();
                break;

            case RTC_TIME_READ:
                if(!rtc.testMode)
                    rtcSetRunning(true);
                rtcPackTime();
                break;

            case RTC_TP_64HZ:
                rtc.tpRate = 64;
                break;

            case RTC_TP_256HZ:
                rtc.tpRate = 256;
                break;

            case RTC_TP_2048HZ:
                rtc.tpRate = 2048;
                break;

            case RTC_TEST:
                rtcSetRunning(false);
                rtc.testMode = true;
                break;
        }

        if(bDebug)
            console.log("ThunderClock uPD1990 command "+command);
    }


    function rtcReadDataOut()
    {
        /*
         * SHIFT and TIME SET expose the serial register directly.
         *
         * REGISTER HOLD and TIME READ make DATA OUT a divider-derived pulse on
         * the physical uPD1990A.  The ThunderClock firmware does not depend on
         * that pulse for normal RTC transfers, but returning a reasonable wall-
         * clock phase here is closer to the chip than leaving a stale bit.
         */
        if(rtc.mode==RTC_SHIFT || rtc.mode==RTC_TIME_SET || rtc.testMode)
            return rtc.dataOut & 1;

        if(rtc.mode==RTC_REGISTER_HOLD)
            return Math.floor(Date.now()/500) & 1;       // 1 Hz square wave

        if(rtc.mode==RTC_TIME_READ)
            return Math.floor(Date.now()/1000) & 1;      // 0.5 Hz square wave

        return rtc.dataOut & 1;
    }


    this.action =
    {
        "SlotROM":
        {
            "RD":{"callback":function(addr,ctx) {
                return thunderclock.readROM(addr,ctx);
            }}
        },
        "SlotIO":
        {
            "RD":{"callback":function(addr,ctx) {
                return thunderclock.readSlotIO(addr,ctx);
            }},
            "WR":{"callback":function(addr,d8,ctx) {
                return thunderclock.writeSlotIO(addr,d8,ctx);
            }}
        },
        "HostROM":
        {
            "RD":{"callback":function(addr,ctx) {
                return thunderclock.readHostROM(addr,ctx);
            }}
        }
    };


    function ownsExpansionROM()
    {
        if(!thunderclock.mount) return false;
        return oEMU.component.IO.ACTION_MAP.Hslot == (thunderclock.mount.slotN-1);
    }


    function selectExpansionROM(ctx)
    {
        // Safe/debugger ROM inspection must not alter shared C8 ownership.
        if(ctx && ctx.bRO===true) return false;
        if(!thunderclock.mount || !thunderclock.mount.ranges || !thunderclock.mount.ranges.HostROM)
            return false;

        var CIO = oEMU.component.IO;
        if(!CIO.ACTION_MAP) return false;

        if(CIO.ACTION_MAP.Hslot == (thunderclock.mount.slotN-1))
            return true;

        CIO.ACTION_MAP.Hslot = thunderclock.mount.slotN-1;

        var range = thunderclock.mount.ranges.HostROM;
        for(var i=range.from;i<=range.to;i++)
            CIO.ACTION_MAP.RD[i] = thunderclock.action.HostROM.RD.callback;

        if(bDebug)
            console.log("ThunderClock Plus claims $C800-$CFFF from PR#"+(thunderclock.mount.slotN-1));

        return true;
    }


    function releaseExpansionROM()
    {
        if(!thunderclock.mount || !oEMU.component.IO.ACTION_MAP) return false;

        var CIO = oEMU.component.IO;
        if(CIO.ACTION_MAP.Hslot != (thunderclock.mount.slotN-1))
            return false;

        CIO.ACTION_MAP.Hslot = null;
        return true;
    }


    this.readROM = function(addr,ctx)
    {
        /*
         * $Cn00-$CnFF is the first 256 bytes of the 2716.  The firmware is
         * slot-independent; unlike Serial Pro, there are no seven preassembled
         * slot pages.
         */
        selectExpansionROM(ctx);

        addr &= 0xFF;
        return THUNDERCLOCKPLUS_ROM[addr] & 0xFF;
    };


    this.readSlotIO = function(addr,ctx)
    {
        /*
         * The real card mirrors its read result over local offsets $0..$F.
         * DATA OUT is physically presented on D7.  Interrupt status on D5 is
         * deliberately deferred until the card's IRQ latch is implemented.
         */
        addr &= 0x0F;
        return rtcReadDataOut() ? 0x80 : 0x00;
    };


    this.writeSlotIO = function(addr,d8,ctx)
    {
        addr &= 0x0F;
        d8 &= 0xFF;

        // Hardware only decodes writes to $C0n0.  $C0n1-$C0nF are ignored.
        if(addr!=0x00)
            return 0x00;

        var nextDataIn = d8 & 0x01;
        var nextClk    = (d8 >> 1) & 0x01;
        var nextStb    = (d8 >> 2) & 0x01;
        var nextCmd    = (d8 >> 3) & 0x07;

        rtc.dataIn = nextDataIn;
        rtc.commandPending = nextCmd;

        /*
         * On the physical card the command pins and DATA IN settle before STB
         * and CLK are applied.  MAME models the same order: command/STB first,
         * then CLK.  Preserve that ordering when both edges occur in one write.
         */
        if(!rtc.stb && nextStb)
            rtcLatchCommand(nextCmd);

        if(!rtc.clk && nextClk)
            rtcShiftClockRising();

        rtc.stb = nextStb;
        rtc.clk = nextClk;
        rtc.control = d8;

        return 0x00;
    };


    this.readHostROM = function(addr,ctx)
    {
        /*
         * $C800-$CFFF maps the complete 2 KiB 2716 ROM without banking.
         */
        var rel_addr;

        if(ctx && Number.isFinite(ctx.rel_addr))
            rel_addr = ctx.rel_addr;
        else if(ctx && Number.isFinite(ctx.line))
            rel_addr = ctx.line + (addr & 0xFF);
        else
            rel_addr = (thunderclock.action.HostROM.base || 0x800) + (addr & 0xFF);

        if(!ownsExpansionROM()) return 0x00;

        var rom_addr = rel_addr - 0x800;
        var d8 = rom_addr>=0 && rom_addr<0x800
            ? THUNDERCLOCKPLUS_ROM[rom_addr]
            : 0x00;

        // Conventional Apple II C8-space release switch.
        if((rel_addr & 0x0FFF)==0x0FFF && !(ctx && ctx.bRO===true))
            releaseExpansionROM();

        return d8 & 0xFF;
    };


    /*
     * Diagnostic helper.  It deliberately exposes a copy rather than the live
     * mutable RTC arrays/state, following the card encapsulation pattern used
     * elsewhere in RetroAppleJS.
     */
    this.getRTCState = function()
    {
        var date = rtcCurrentDate();

        return {
             "date":new Date(date.getTime())
            ,"running":rtc.running
            ,"mode":rtc.mode
            ,"control":rtc.control & 0xFF
            ,"dataIn":rtc.dataIn & 1
            ,"dataOut":rtcReadDataOut() & 1
            ,"tpRate":rtc.tpRate
            ,"testMode":rtc.testMode
            ,"shift":Array.from(rtc.shift)
        };
    };


    function resetInterface()
    {
        releaseExpansionROM();

        /*
         * RESET affects the Apple-side latch/interface, not the battery-backed
         * calendar.  Resume the counter and return the external control lines to
         * a benign low state while preserving the current date/time.
         */
        rtcSetRunning(true);
        rtc.mode = RTC_REGISTER_HOLD;
        rtc.commandPending = RTC_REGISTER_HOLD;
        rtc.control = 0x00;
        rtc.dataIn = 0;
        rtc.dataOut = 0;
        rtc.clk = 0;
        rtc.stb = 0;
        rtc.testMode = false;
        rtc.tpRate = 64;
    }


    this.reset = function()
    {
        resetInterface();
    };


    this.restart = function()
    {
        resetInterface();
    };
}
