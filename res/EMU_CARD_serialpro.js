    {
        return RTC_UPDATE_INTERRUPT_ROUTE=="nmi"
            ? rtcAssertNMI()
            : rtcAssertIRQ();
    }

    function rtcClearInterrupt()
    {
        return RTC_UPDATE_INTERRUPT_ROUTE=="nmi"
            ? rtcClearNMI()
            : rtcClearIRQ();
    }

    /*
     * Keep 6551 register decoding independent from the source of the register
     * bytes.  The Serial Pro has two related serial states:
     *
     *   RTC battery RAM $23/$24  = saved/configured CONTROL + COMMAND
     *   acia.control/command     = live 6551 hardware registers
     *
     * The ROM control panel edits the saved bytes first; firmware subsequently
     * copies them into the live 6551 when it (re)initializes the interface.
     */
    function serialWordLengthFromControl(control)
    {
        return 8 - (((control & 0xFF) >> 5) & 0x03);
    }
    

    function aciaWordLength()
    {
        return serialWordLengthFromControl(acia.control);
    }

    function aciaDataMask()
    {
        return (0xFF >> (8-aciaWordLength())) & 0xFF;
    }

    function serialParityFromCommand(command)
    {
        command &= 0xFF;
        if((command & 0x20)==0) return "none";
        return ["odd","even","mark","space"][(command >> 6) & 0x03];
    }

    function aciaParity()
    {
        return serialParityFromCommand(acia.command);
    }

    function aciaParityChecked()
    {
        if((acia.command & 0x20)==0) return false;
        return ((acia.command >> 6) & 0x03) < 2;    // odd/even only
    }

    function serialStopBitsFromRegisters(control,command)
    {
        control &= 0xFF;
        command &= 0xFF;
        if((control & 0x80)==0) return 1;

        var bits = serialWordLengthFromControl(control);
        var parity = serialParityFromCommand(command);
        if(bits==5 && parity=="none") return 1.5;
        if(bits==8 && parity!="none") return 1;
        return 2;
    }

    function aciaStopBits()
    {
        return serialStopBitsFromRegisters(acia.control,acia.command);
    }

    function serialBaudFromControl(control)
    {
        return ACIA_BAUD_TABLE[control & 0x0F];
    }

    function aciaBaudRate()
    {
        return serialBaudFromControl(acia.control);
    }

    function serialFormatSignature(control,command)
    {
        return [
             serialBaudFromControl(control)
            ,serialWordLengthFromControl(control)
            ,serialParityFromCommand(command)
            ,serialStopBitsFromRegisters(control,command)
            ,(control & 0x10)!=0 ? "rx=tx" : "rx=ext"
        ].join("/");
    }

    function serialFormatLabel(control,command)
    {
        var baud = serialBaudFromControl(control);
        var parity = serialParityFromCommand(command);
        var parityLetter = {
             "none":"N"
            ,"odd":"O"
            ,"even":"E"
            ,"mark":"M"
            ,"space":"S"
        }[parity] || "?";

        return String(baud==null ? "EXT" : baud)
            +" "+serialWordLengthFromControl(control)
            +parityLetter
            +String(serialStopBitsFromRegisters(control,command));
    }

    function serialConfiguredState()
    {
        // Until the AE/$55 NVRAM signature exists, preserve the pre-existing
        // browser behavior by presenting the live ACIA state.  Once firmware
        // initializes the battery RAM, $23/$24 become authoritative for SER.
        var nvramValid = rtc.ram[0x20]==0xAE && rtc.ram[0x21]==0x55;
        var control = nvramValid ? (rtc.ram[0x23] & 0xFF) : (acia.control & 0xFF);
        var command = nvramValid ? (rtc.ram[0x24] & 0xFF) : (acia.command & 0xFF);

        return {
             "valid":nvramValid
            ,"control":control
            ,"command":command
            ,"baud":serialBaudFromControl(control)
            ,"dataBits":serialWordLengthFromControl(control)
            ,"parity":serialParityFromCommand(command)
            ,"stopBits":serialStopBitsFromRegisters(control,command)
            ,"rxClockInternal":(control & 0x10)!=0
        };
    }

    function aciaCPUMultiplier()
    {
        var base = typeof(_o)!="undefined" ? Number(_o.CPU_ClocksTicks_s) : NaN;
        var target = typeof(_o)!="undefined" ? Number(_o.CPU_TargetTicks_s) : NaN;
        return Number.isFinite(base) && base>0 && Number.isFinite(target) && target>0
            ? target/base
            : 1;
    }

    function aciaEffectiveBaudRate()
    {
        var baud = aciaBaudRate();
        if(!Number.isFinite(baud)) return baud;
        return state.cpuSync ? baud*aciaCPUMultiplier() : baud;
    }

    function aciaFrameBits()
    {
        return 1                                  // start bit
            + aciaWordLength()
            + (aciaParity()=="none" ? 0 : 1)
            + aciaStopBits();
    }

    function aciaFrameTicks()
    {
        var baud = aciaBaudRate();
        var base = typeof(_o)!="undefined" ? Number(_o.CPU_ClocksTicks_s) : NaN;
        if(!Number.isFinite(baud) || baud<=0 || !Number.isFinite(base) || base<=0)
            return Infinity;
        return base*aciaFrameBits()/baud;
    }

    function aciaClockScale()
    {
        if(state.cpuSync) return 1;
        var multiplier = aciaCPUMultiplier();
        return multiplier>0 ? 1/multiplier : 1;
    }

    function aciaClockNow(ctx)
    {
        if(ctx && ctx.io && typeof(ctx.io.getClockTicks)=="function")
            return Number(ctx.io.getClockTicks());

        if(typeof(apple2plus)=="object" && apple2plus &&
           typeof(apple2plus.hwObj)=="function")
        {
            var hw = apple2plus.hwObj();
            if(hw && hw.io && typeof(hw.io.getClockTicks)=="function")
                return Number(hw.io.getClockTicks());
        }
        return Number(acia.lastClockTick) || 0;
    }

    function aciaAdvanceTiming(serialTicks)
    {
        var frameTicks = aciaFrameTicks();
        if(!Number.isFinite(frameTicks) || frameTicks<=0 ||
           !Number.isFinite(serialTicks) || serialTicks<=0)
            return false;

        if(acia.txBusy)
        {
            acia.txTicks += serialTicks;
            if(acia.txTicks>=frameTicks)
            {
                var txByte = acia.txData & aciaDataMask();
                acia.txTicks = 0;
                acia.txBusy = false;

                if(!aciaBreakActive())
                    serialLineTransmitByte(txByte);


                acia.txEmpty = true;
                if(aciaTransmitIRQEnabled())
                    aciaAssertIRQ(ACIA_IRQ_TX);
            }
        }

        if(acia.rxBusy)
        {
            acia.rxTicks += serialTicks;
            if(acia.rxTicks>=frameTicks)
            {
                acia.rxTicks = 0;
                acia.rxBusy = false;
                acia.rxData = acia.rxShift & aciaDataMask();
                acia.rxFull = true;
                if(aciaReceiverIRQEnabled())
                    aciaAssertIRQ(ACIA_IRQ_RX);
            }
        }
        return true;
    }

    function aciaSyncClock(clockTick)
    {
        clockTick = Number(clockTick);
        if(!Number.isFinite(clockTick)) return false;

        var previous = Number(acia.lastClockTick);
        acia.lastClockTick = clockTick;
        if(!Number.isFinite(previous) || clockTick<=previous) return true;

        return aciaAdvanceTiming((clockTick-previous)*aciaClockScale());
    }

    function aciaSyncNow(ctx)
    {
        return aciaSyncClock(aciaClockNow(ctx));
    }

    function aciaDTRAsserted()
    {
        return (acia.command & 0x01)!=0;             // DTRB low
    }

    function aciaReceiverIRQEnabled()
    {
        return aciaDTRAsserted() && (acia.command & 0x02)==0;
    }

    function aciaTransmitMode()
    {
        return (acia.command >> 2) & 0x03;
    }

    function aciaEchoMode()
    {
        return (acia.command & 0x10)!=0;
    }

    function aciaRTSAsserted()
    {
        if(aciaEchoMode()) return true;              // echo mode forces RTSB low
        return aciaTransmitMode()!=0;                // TIC 00 is RTSB high
    }

    function aciaTransmitIRQEnabled()
    {
        return aciaDTRAsserted() && !aciaEchoMode() && aciaTransmitMode()==1;
    }

    function aciaBreakActive()
    {
        return !aciaEchoMode() && aciaTransmitMode()==3;
    }

    function aciaEvaluateEnabledInterrupts()
    {
        if(aciaReceiverIRQEnabled())
        {
            if(acia.rxFull)
                aciaAssertIRQ(ACIA_IRQ_RX);
            if(acia.modemStatusLatched)
                aciaAssertIRQ(ACIA_IRQ_MODEM);
        }

        if(aciaTransmitIRQEnabled() && acia.txEmpty)
            aciaAssertIRQ(ACIA_IRQ_TX);
    }

    function aciaHardwareReset()
    {
        acia.command = 0x00;
        acia.control = 0x00;
        acia.rxData = 0x00;
        acia.rxFull = false;
        acia.rxErrors = 0x00;
        acia.rxShift = 0x00;
        acia.rxBusy = false;
        acia.rxTicks = 0;
        acia.txData = 0x00;
        acia.txEmpty = true;
        acia.txBusy = false;
        acia.txTicks = 0;
        acia.lastClockTick = aciaClockNow();
        acia.dsrStatusReady = acia.dsrReady;
        acia.dcdStatusDetected = acia.dcdDetected;
        acia.modemStatusLatched = false;
        aciaClearIRQ();

        // A browser serial port stays physically open across Apple II RESET.
        serialPhysicalCheckConfiguration();
        serialPhysicalSyncOutputs();     
    }

    function aciaProgramReset()
    {
        // Legacy 6551 programmed reset: clear Command bits 4..0 and Status
        // overrun.  Parity selection bits 7..5 and Control are unchanged.
        acia.command &= 0xE0;
        acia.rxErrors &= ~0x04;
        aciaClearIRQ();
        serialPhysicalCheckConfiguration();
        serialPhysicalSyncOutputs();
    }

    function aciaWriteCommand(value)
    {
        acia.command = value & 0xFF;

        // Leaving a blocked condition may start a waiting transmitter frame.
        aciaTryTransmit();
        aciaEvaluateEnabledInterrupts();
        serialPhysicalCheckConfiguration();
        serialPhysicalSyncOutputs();
    }

    function aciaWriteControl(value)
    {
        acia.control = value & 0xFF;
        aciaTryTransmit();
        aciaPrimeReceiver();
        serialPhysicalCheckConfiguration();
    }

    /*
     * Receiver bridge. serialTerminalState.toCard[] is the remote-end byte
     * stream waiting on the simulated line.  A byte first occupies a simple
     * receive-shift stage for one configured frame time; only then does RDRF
     * become visible to the CPU.
     *
     * This stage deliberately retains the existing one-byte receive holding
     * model: the next queued frame starts after DATA is consumed.  Detailed
     * overrun behavior remains a later refinement.
     */
    function aciaPrimeReceiver()
    {
        if(acia.rxFull || acia.rxBusy) return true;
        if(!serialTerminalState || !serialTerminalState.toCard) return false;
        if(!serialTerminalState.toCard.length) return false;
        if((acia.control & 0x10)==0)  return false;     // external receiver clock
        if(!Number.isFinite(aciaBaudRate())) return false;

        acia.rxShift = serialTerminalState.toCard.shift() & aciaDataMask();
        acia.rxTicks = 0;
        acia.rxBusy = true;       
        return true;
    }

    function aciaRXPending()
    {
        return !!acia.rxFull;
    }

    function aciaReadData(ctx)
    {
        if(!aciaRXPending())
            return acia.rxData & 0xFF;

        // Safe debugger/memory inspection must not consume the receive register.
        if(ctx && ctx.bRO===true)
            return acia.rxData & 0xFF;

        var value = acia.rxData & 0xFF;
        acia.rxFull = false;        
        acia.rxErrors = 0x00;       // PE/FE/OVRN clear after DATA read
        // Start, but do not instantly complete, the next queued remote frame.
        aciaPrimeReceiver();
        return value;
    }

    function aciaReadStatus(ctx)
    {
        var status = acia.rxErrors & 0x07;

        if(acia.rxFull)           status |= 0x08;  // RDRF
        if(acia.txEmpty)          status |= 0x10;  // TDRE
        if(!acia.dcdStatusDetected) status |= 0x20;// DCD high/not detected
        if(!acia.dsrStatusReady)    status |= 0x40;// DSR high/not ready
        if(acia.irq)              status |= 0x80;

        if(!(ctx && ctx.bRO===true))
        {
            var hadModemLatch = acia.modemStatusLatched;
            aciaClearIRQ();                         // Status read clears IRQ bit

            /*
             * DCD/DSR status is latched on the first transition.  If either
             * physical input changed again before Status was read, expose the
             * new level now and immediately generate the next modem interrupt.
             */
            if(hadModemLatch)
            {
                acia.modemStatusLatched = false;

                if(acia.dcdStatusDetected!=acia.dcdDetected ||
                   acia.dsrStatusReady!=acia.dsrReady)
                {
                    acia.dcdStatusDetected = acia.dcdDetected;
                    acia.dsrStatusReady = acia.dsrReady;
                    acia.modemStatusLatched = true;

                    if(aciaReceiverIRQEnabled())
                        aciaAssertIRQ(ACIA_IRQ_MODEM);
                }
            }
        }

        return status & 0xFF;
    }

    function aciaTryTransmit()
    {
        if(acia.txEmpty || acia.txBusy || !acia.ctsClear)
            return false;
        if(!Number.isFinite(aciaBaudRate()))
            return false;

        acia.txTicks = 0;
        acia.txBusy = true;
        return true;
    }

    function aciaWriteData(d8)
    {
        acia.txData = d8 & 0xFF;
        acia.txEmpty = false;
        aciaTryTransmit();
    }
    function aciaLatchModemStatusChange()
    {
        if(acia.modemStatusLatched)
            return;

        acia.dcdStatusDetected = acia.dcdDetected;
        acia.dsrStatusReady = acia.dsrReady;
        acia.modemStatusLatched = true;

        if(aciaReceiverIRQEnabled())
            aciaAssertIRQ(ACIA_IRQ_MODEM);
    }

