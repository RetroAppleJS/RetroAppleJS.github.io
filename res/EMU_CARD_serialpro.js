    function serialTerminalRemember(kind,text)
    {
        text = String(text===undefined ? "" : text);
        if(!text.length) return;

        var rows = serialTerminalState.transcript;
        var last = rows.length ? rows[rows.length-1] : null;

        if(last && last.kind===kind && !last.bytes && last.text.length<4096)
            last.text += text;
        else
            rows.push({"kind":kind,"text":text});

        serialTerminalState.transcriptChars += text.length;
        while(serialTerminalState.transcriptChars>65536 && rows.length>1)
        {
            var dropped = rows.shift();
            serialTerminalState.transcriptChars -= dropped.bytes
                ? dropped.bytes.length
                : dropped.text.length;
        }
    }

    function serialTerminalRememberByte(d8)
    {
        d8 &= 0xFF;

        var rows = serialTerminalState.transcript;
        var last = rows.length ? rows[rows.length-1] : null;

        if(last && last.kind==="rx" && last.bytes && last.bytes.length<4096)
            last.bytes.push(d8);
        else
            rows.push({"kind":"rx","bytes":[d8]});

        serialTerminalState.transcriptChars++;
        while(serialTerminalState.transcriptChars>65536 && rows.length>1)
        {
            var dropped = rows.shift();
            serialTerminalState.transcriptChars -= dropped.bytes
                ? dropped.bytes.length
                : dropped.text.length;
        }
    }

    function serialTerminalDisplayByte(d8)
    {
        d8 &= 0xFF;

        /*
         * Apple II text normally travels with bit 7 set. APPLE ASCII mode is
         * intended for LIST/PR# capture and printer-like output: strip bit 7
         * before interpreting CR/LF/TAB and printable ASCII. RAW mode retains
         * the original diagnostic rendering of non-printing 8-bit values.
         */
        var ascii = serialTerminalState.displayMode==="ascii";
        var c = ascii ? (d8 & 0x7F) : d8;

        if(c===0x0D)
        {
            serialTerminalState.lastRxCR = true;
            return "\n";
        }

        if(c===0x0A)
        {
            if(serialTerminalState.lastRxCR)
            {
                serialTerminalState.lastRxCR = false;
                return "";
            }
            return "\n";
        }

        serialTerminalState.lastRxCR = false;
        if(c===0x09) return "\t";

        if(ascii)
        {
            // Backspace/NUL and other Apple control traffic should not turn a
            // human-readable printer/listing stream back into byte notation.
            if(c===0x0C) return "\n";              // form feed: readable break
            if(c>=0x20 && c<=0x7E) return String.fromCharCode(c);
            return "";
        }

        if(c>=0x20 && c<=0x7E) return String.fromCharCode(c);

        // Keep otherwise non-printing octets visible in the terminal.
        return "[$"+serialTerminalHexByte(d8)+"]";
    }

    function serialTerminalRenderRow(row)
    {
        if(row && row.bytes)
        {
            var text = "";
            for(var i=0;i<row.bytes.length;i++)
                text += serialTerminalDisplayByte(row.bytes[i]);
            return text;
        }

        return row && row.text ? row.text : "";
    }

    function serialTerminalRenderTranscript(terminal)
    {
        if(!terminal || !terminal._o || !terminal._o.DOM) return false;

        terminal._o.DOM.output.innerHTML = "";
        serialTerminalState.lastRxCR = false;

        var rows = serialTerminalState.transcript;
        for(var i=0;i<rows.length;i++)
        {
            var text = serialTerminalRenderRow(rows[i]);
            if(text.length) terminal.write(text,rows[i].kind);
        }

        return true;
    }

    this.serialTerminalQueueLine = function(line)
    {
        line = String(line===undefined ? "" : line);
        var bytes = new Uint8Array(line.length + 1);

        for(var i=0;i<line.length;i++)
             bytes[i] = line.charCodeAt(i) & 0xFF;

        // ENTER on the terminal is the remote endpoint sending CR.
        bytes[line.length] = 0x0D;
        serialTerminalRemember("tx",">"+line+"\n");
        return serialLineInjectBytes(
            bytes,
            {"source":"oterm"}
        );

    };

    this.serialTerminalPending = function()
    {
        return serialTerminalState.toCard.length + (acia.rxFull ? 1 : 0) + (acia.rxBusy ? 1 : 0);
    };

    /*
     * Diagnostic/configuration API for the simulated modem side.
     * Boolean line names use their logical meaning, hiding the 6551's active-low
     * pin names: cts=true means CTSB low/clear-to-send, dcd=true means carrier
     * detected, and dsr=true means data set ready.
     */
    this.serialTerminalACIAState = function()
    {
        aciaSyncNow();
        return aciaDescribe();
    };

    this.serialTerminalSetModemLines = function(lines)
    {
        aciaSyncNow();
        lines = lines || {};

        var oldCTS = acia.ctsClear;
        var modemChanged = false;

        if(Object.prototype.hasOwnProperty.call(lines,"cts"))
            acia.ctsClear = !!lines.cts;

        if(Object.prototype.hasOwnProperty.call(lines,"dcd"))
        {
            var nextDCD = !!lines.dcd;
            modemChanged = modemChanged || nextDCD!=acia.dcdDetected;
            acia.dcdDetected = nextDCD;
        }

        if(Object.prototype.hasOwnProperty.call(lines,"dsr"))
        {
            var nextDSR = !!lines.dsr;
            modemChanged = modemChanged || nextDSR!=acia.dsrReady;
            acia.dsrReady = nextDSR;
        }

        if(modemChanged)
            aciaLatchModemStatusChange();

        // CTSB returning low allows a held transmitter frame to begin.
        if(!oldCTS && acia.ctsClear)
            aciaTryTransmit();

        return aciaDescribe();
    };

    this.serialTerminalReadByte = function()
    {
        aciaSyncNow();
        // Diagnostic helper: consume through the same receive-register path
        // used by CPU reads so console tests cannot bypass Stage 2C semantics.
        if(!acia.rxFull)
            aciaPrimeReceiver();

        return acia.rxFull ? aciaReadData(null) : null;
    };

    this.serialTerminalWriteByte = function(d8)
    {
        d8 &= 0xFF;
        serialTerminalRememberByte(d8);

        var text = serialTerminalDisplayByte(d8);
        if(!text.length) return d8 & 0xFF;

        var terminal = serialTerminalLive();
        if(terminal) terminal.write(text,"rx");

        return d8 & 0xFF;
    };

    this.serialTerminalWriteText = function(text)
    {
        text = String(text===undefined ? "" : text);
        for(var i=0;i<text.length;i++)
            serialpro.serialTerminalWriteByte(text.charCodeAt(i) & 0xFF);
        return text.length;
    };

    this.serialTerminalClear = function()
    {
        serialTerminalState.transcript = [];
        serialTerminalState.transcriptChars = 0;
        serialTerminalState.lastRxCR = false;

        var terminal = serialTerminalLive();
        if(terminal) terminal.clear();
        return true;
    };

    function serialTerminalSelectionInsideOutput(terminal)
    {
        if(!terminal || !terminal._o || !terminal._o.DOM ||
           typeof(window)==="undefined" || typeof(window.getSelection)!="function")
            return false;

        var selection = window.getSelection();
        if(!selection || selection.rangeCount<1 || selection.isCollapsed)
            return false;

        var output = terminal._o.DOM.output;
        function inside(node)
        {
            if(!node) return false;
            if(node.nodeType===3) node = node.parentNode;
            return node===output || output.contains(node);
        }

        return inside(selection.anchorNode) || inside(selection.focusNode);
    }

    function serialTerminalProtectStreaming(terminal)
    {
        if(!terminal || terminal._serialProWriteWrapped) return false;

        var dom = terminal._o && terminal._o.DOM;
        if(!dom) return false;

        // Some emulator-level UI styles disable text selection. Override that
        // locally: the Serial Pro output is intentionally printer-like text.
        if(dom.output && dom.output.style)
        {
            dom.output.style.userSelect = "text";
            dom.output.style.webkitUserSelect = "text";
        }

        var baseWrite = terminal.write.bind(terminal);
        terminal.write = function(text,channel)
        {
            var input = dom.input;
            var preserveSelection = serialTerminalSelectionInsideOutput(terminal);
            var scrollTop = dom.container.scrollTop;
            var scrollLeft = dom.container.scrollLeft;

            // oTERM write() currently calls resetCommand(). Preserve an input
            // line being typed while asynchronous serial bytes continue to
            // arrive; this also prevents a stream from stealing edit state.
            var inputValue = input ? input.value : "";
            var inputActive = input && document.activeElement===input;
            var selectionStart = input ? input.selectionStart : 0;
            var selectionEnd = input ? input.selectionEnd : 0;

            var result = baseWrite(text,channel);

            if(input)
            {
                input.value = inputValue;
                // Never refocus the live command field across a streamed write
                // while browser output text is selected; focus would collapse
                // the Range the user is trying to keep/copy.
                if(inputActive && !preserveSelection)
                {
                    try { input.focus({"preventScroll":true}); }
                    catch(ignore) { input.focus(); }
                    try { input.setSelectionRange(selectionStart,selectionEnd); }
                    catch(ignore) {}
                }
            }

            /*
             * Appending new Text nodes does not invalidate the browser Range.
             * Suppress oTERM's automatic scroll-to-input while a non-collapsed
             * output selection exists so the selected visual scope stays put
             * even though the stream continues growing below it.
             */
            if(preserveSelection)
            {
                dom.container.scrollTop = scrollTop;
                dom.container.scrollLeft = scrollLeft;
            }

            return result;
        };

        terminal._serialProWriteWrapped = true;
        return true;
    }

