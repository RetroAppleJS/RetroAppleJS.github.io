// Discovery container. Apple2IO mounts a separate live instance.
if(oEMU===undefined) var oEMU = {"component":{"IO":{"SerialPro":new SerialProCard()}}}
else oEMU.component.IO.SerialPro = new SerialProCard();


function SerialProCard()
{
    const bDebug = false;

    this.id = {"PCODE":"SPC", "icon":"fa fa-terminal"};

    var state =
    {
        "active":true
    };

    this.state = state;

    var serialpro = this;       // stand-in where 'this' is absent inside callbacks


    this.action =
    {
        "SlotROM":
        {
            "RD":{"callback":function(addr,ctx) {
                return serialpro.readROM(addr,ctx);
            }}
        },
        "HostROM":
        {
            "RD":{"callback":function(addr,ctx) {
                return serialpro.readHostROM(addr,ctx);
            }}
        }
    };


    function ownsExpansionROM()
    {
        if(!serialpro.mount) return false;
        return oEMU.component.IO.ACTION_MAP.Hslot == (serialpro.mount.slotN-1);
    }


    function selectExpansionROM(ctx)
    {
        // Safe/debugger ROM inspection must not alter shared C8 ownership.
        if(ctx && ctx.bRO===true) return false;
        if(!serialpro.mount || !serialpro.mount.ranges || !serialpro.mount.ranges.HostROM)
            return false;

        var CIO = oEMU.component.IO;
        if(!CIO.ACTION_MAP) return false;

        if(CIO.ACTION_MAP.Hslot == (serialpro.mount.slotN-1))
            return true;

        CIO.ACTION_MAP.Hslot = serialpro.mount.slotN-1;

        /*
         * Match the existing shared HostROM mechanism used by other cards:
         * reading this card's slot page selects its $C800-$CFFF view.
         */
        var range = serialpro.mount.ranges.HostROM;
        for(var i=range.from;i<=range.to;i++)
            CIO.ACTION_MAP.RD[i] = serialpro.action.HostROM.RD.callback;

        if(bDebug)
            console.log("Serial Pro claims $C800-$CFFF from PR#"+(serialpro.mount.slotN-1));

        return true;
    }


    function releaseExpansionROM()
    {
        if(!serialpro.mount || !oEMU.component.IO.ACTION_MAP) return false;

        var CIO = oEMU.component.IO;
        if(CIO.ACTION_MAP.Hslot != (serialpro.mount.slotN-1))
            return false;

        CIO.ACTION_MAP.Hslot = null;
        return true;
    }


    this.readROM = function(addr,ctx)
    {
        /*
         * $Cn00-$CnFF slot-page view.
         *
         * The address mapping is final, but the authentic v2.0 slot-page bytes
         * are not present in the supplied 2 KiB HostROM dump yet.
         */
        selectExpansionROM(ctx);

        addr &= 0xFF;
        return SERIALPRO_SLOT_ROM[addr] & 0xFF;
    };


    this.readHostROM = function(addr,ctx)
    {
        /*
         * $C800-$CFFF shared expansion-ROM view.
         *
         * Apple2IO must provide ctx.rel_addr (C000-relative full bus address)
         * so all eight 256-byte HostROM pages can be distinguished.  A small
         * generic Apple2IO context patch accompanies this driver.
         */
        var rel_addr;

        if(ctx && Number.isFinite(ctx.rel_addr))
            rel_addr = ctx.rel_addr;
        else if(ctx && Number.isFinite(ctx.line))
            rel_addr = ctx.line + (addr & 0xFF);
        else
            rel_addr = (serialpro.action.HostROM.base || 0x800) + (addr & 0xFF);

        if(!ownsExpansionROM()) return 0x00;

        var rom_addr = rel_addr - 0x800;
        var d8 = rom_addr>=0 && rom_addr<SERIALPRO_HOST_ROM.length
            ? SERIALPRO_HOST_ROM[rom_addr]
            : 0x00;

        // $CFFF conventionally releases the shared C8 expansion-ROM window.
        if((rel_addr & 0x0FFF)==0x0FFF && !(ctx && ctx.bRO===true))
            releaseExpansionROM();

        return d8 & 0xFF;
    };


    this.reset = function()
    {
        releaseExpansionROM();
    };


    this.restart = function()
    {
        releaseExpansionROM();
    };
}
