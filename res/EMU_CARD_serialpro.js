    function serialTerminalCopyText()
    {
        var terminal = serialTerminalLive();
        if(!terminal || !terminal._o || !terminal._o.DOM) return "";
        // The toolbar pictogram is deliberately COPY ALL.  A user's explicit
        // selection remains available to the browser's normal Cmd/Ctrl-C.
        var output = terminal._o.DOM.output;
        return output.innerText!==undefined ? output.innerText : output.textContent;
    }

    this.serialTerminalCopy = async function()
    {
        var text = serialTerminalCopyText();
        if(!text.length) return 0;

        var copied = false;
        try
        {
            if(typeof(navigator)!=="undefined" && navigator.clipboard &&
               typeof(navigator.clipboard.writeText)==="function")
            {
                await navigator.clipboard.writeText(text);
                copied = true;
            }
        }
        catch(ignore) {}

        if(!copied)
        {
            var area = document.createElement("textarea");
            area.value = text;
            area.setAttribute("readonly","");
            area.style.cssText = "position:fixed;left:-10000px;top:-10000px;";
            document.body.appendChild(area);
            area.select();
            try { copied = document.execCommand("copy"); } catch(ignore) {}
            document.body.removeChild(area);
        }

        return copied ? text.length : 0;
    };

