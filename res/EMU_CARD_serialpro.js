    function ownsExpansionROM()
    {
        if(!serialpro.mount) return false;
        return oEMU.component.IO.ACTION_MAP.Hslot == (serialpro.mount.slotN-1);
    }


    function selectExpansionROM(ctx)
    {
        // Safe/debugger ROM inspection must not alter shared C8 ownership.
        if(ctx && ctx.bRO===true) return false;
        if(!serialpro.mount || !serialpro.mount.ranges || !serialpro.mount.ranges.HostROM)
            return false;

        var CIO = oEMU.component.IO;
        if(!CIO.ACTION_MAP) return false;

        if(CIO.ACTION_MAP.Hslot == (serialpro.mount.slotN-1))
            return true;

        CIO.ACTION_MAP.Hslot = serialpro.mount.slotN-1;

        /*
         * Apple II expansion-ROM selection is independent from the Serial Pro's
         * own EPROM bank register.  Reading this card's $Cnxx page claims the
         * shared $C800-$CFFF window for this slot; BANKCLR/BANKREG merely choose
         * which 2 KiB quarter of the card's 27C64 appears in that window.
         */
        var range = serialpro.mount.ranges.HostROM;
        for(var i=range.from;i<=range.to;i++)
            CIO.ACTION_MAP.RD[i] = serialpro.action.HostROM.RD.callback;

        if(bDebug)
            console.log("Serial Pro claims $C800-$CFFF from PR#"+(serialpro.mount.slotN-1));

        return true;
    }


    function releaseExpansionROM()
    {
        if(!serialpro.mount || !oEMU.component.IO.ACTION_MAP) return false;

        var CIO = oEMU.component.IO;
        if(CIO.ACTION_MAP.Hslot != (serialpro.mount.slotN-1))
            return false;

        CIO.ACTION_MAP.Hslot = null;
        return true;
    }

    function physicalHostROMBank()
    {
        /*
         * Reverse-engineered from the complete v2.0 EPROM and its dispatcher:
         *
         *     selector .... ..00 -> EPROM $0000-$07FF
         *     selector .... ..01 -> EPROM $0800-$0FFF
         *     selector .... ..10 -> EPROM $1000-$17FF
         *     selector .... ..11 -> EPROM $1800-$1FFF
         *
         * AE documents the two write-only switches, but not this bit-level
         * encoding.  The firmware proves the low-two-bit relationship: e.g.
         * $01 and $09 use physical bank 1, while $02/$0A/$12 use bank 2.
         */
        return state.romSelector & 0x03;
    }    

    function rtcIsBinary()
    {
        return (rtc.ram[0x0B] & 0x04) != 0;
    }

    function rtcIs24Hour()
    {
        return (rtc.ram[0x0B] & 0x02) != 0;
    }

    function rtcToBCD(value)
    {
        value = Math.max(0,Math.floor(value));
        return (((Math.floor(value/10) % 10) << 4) | (value % 10)) & 0xFF;
    }

    function rtcFromBCD(value)
    {
        return (((value >> 4) & 0x0F) * 10) + (value & 0x0F);
    }

    function rtcEncode(value)
    {
        return rtcIsBinary() ? (value & 0xFF) : rtcToBCD(value);
    }

    function rtcDecode(value)
    {
        return rtcIsBinary() ? (value & 0xFF) : rtcFromBCD(value);
    }

    function rtcCurrentDate()
    {
        var timeMs = rtc.baseTimeMs;

        // Register B bit 7 is SET/HOLD.  While clear the clock advances at
        // wall-clock speed; while set it remains frozen for coherent updates.
        if((rtc.ram[0x0B] & 0x80)==0)
            timeMs += Date.now() - rtc.hostBaseMs;

        return new Date(timeMs);
    }

    function rtcRebase(date)
    {
        rtc.baseTimeMs = date.getTime();
        rtc.hostBaseMs = Date.now();

        // A programmed clock jump must not be mistaken for a natural
        // update-ended boundary on the next peripheral timing sample.
        rtc.lastUpdateSecond = Math.floor(rtc.baseTimeMs/1000);
    }

    function rtcUpdateEndedPoll()
    {
        var second = Math.floor(rtcCurrentDate().getTime()/1000);

        // SET/HOLD suppresses time updates. Keep the detector aligned with the
        // frozen image so releasing SET waits for the next real second edge.
        if((rtc.ram[0x0B] & RTC_B_SET)!=0)
        {
            rtc.lastUpdateSecond = second;
            return false;
        }

        if(!Number.isFinite(rtc.lastUpdateSecond))
        {
            rtc.lastUpdateSecond = second;
            return false;
        }

        if(second==rtc.lastUpdateSecond)
            return false;

        // A delayed emulator slice can cross more than one wall-clock second.
        // Register C is level/flag based, so one pending UF is sufficient.
        rtc.lastUpdateSecond = second;
        rtc.ram[0x0C] |= RTC_C_UF;

        if((rtc.ram[0x0B] & RTC_B_UIE)!=0)
        {
            rtc.ram[0x0C] |= RTC_C_IRQF;
            rtcAssertInterrupt();
        }
        return true;
    }

    function rtcIRQSampleTicks()
    {
        var base = typeof(_o)!="undefined" ? Number(_o.CPU_ClocksTicks_s) : NaN;
        return Number.isFinite(base) && base>0
            ? Math.max(1,Math.floor(base/32))       // about 32 polls/sec at x1
            : 32768;
    }

    function rtcSyncClock(clockTick)
    {
        clockTick = Number(clockTick);
        if(!Number.isFinite(clockTick)) return false;

        var previous = Number(rtc.lastIRQSampleTick);

        // CPU RESET/restart can move the completed-cycle counter backwards.
        if(!Number.isFinite(previous) || clockTick<previous)
        {
            rtc.lastIRQSampleTick = clockTick;
            rtc.lastUpdateSecond = Math.floor(rtcCurrentDate().getTime()/1000);
            return true;
        }

        if(clockTick-previous < rtcIRQSampleTicks())
            return true;

        rtc.lastIRQSampleTick = clockTick;
        rtcUpdateEndedPoll();
        return true;
    }

    function rtcEncodeHour(date)
    {
        var hour = date.getHours();

        if(rtcIs24Hour())
            return rtcEncode(hour);

        var pm = hour >= 12;
        hour %= 12;
        if(hour==0) hour = 12;
        return rtcEncode(hour) | (pm ? 0x80 : 0x00);
    }

    function rtcDecodeHour(value)
    {
        if(rtcIs24Hour())
            return Math.min(23,rtcDecode(value & 0x7F));

        var pm = (value & 0x80) != 0;
        var hour = rtcDecode(value & 0x7F);
        if(hour<1) hour = 1;
        if(hour>12) hour = 12;
        if(hour==12) hour = 0;
        return hour + (pm ? 12 : 0);
    }

    function rtcReadData(ctx)
    {
        var reg = rtc.address & 0x3F;
        var date = rtcCurrentDate();

        switch(reg)
        {
            case 0x00: return rtcEncode(date.getSeconds());
            case 0x01: return rtc.ram[reg];                 // seconds alarm
            case 0x02: return rtcEncode(date.getMinutes());
            case 0x03: return rtc.ram[reg];                 // minutes alarm
            case 0x04: return rtcEncodeHour(date);
            case 0x05: return rtc.ram[reg];                 // hours alarm
            case 0x06:
            {
                // 6818 day-of-week range is 1..7.  JavaScript uses Sunday=0.
                var weekday = ((date.getDay() + rtc.weekdayOffset) % 7) + 1;
                return rtcEncode(weekday);
            }
            case 0x07: return rtcEncode(date.getDate());
            case 0x08: return rtcEncode(date.getMonth()+1);
            case 0x09: return rtcEncode(date.getFullYear()%100);

            case 0x0A:
                /*
                 * Register A bit 7 is Update-In-Progress.  RetroAppleJS does not
                 * model the 1.984 ms ripple/update interval cycle-accurately; a
                 * JavaScript Date snapshot is atomic for our purposes, so UIP is
                 * deliberately reported clear.  This is sufficient for the AE
                 * firmware's $CsA9 safe-clock-image loop.
                 */
                return rtc.ram[0x0A] & 0x7F;

            case 0x0B:
                return rtc.ram[0x0B];

            case 0x0C:
            {
                // Register C reports the latched interrupt flags. A real CPU read
                // acknowledges all RTC sources and releases the RTC IRQ request.
                // Debugger/read-only inspection must remain side-effect free.
                var flags = rtc.ram[0x0C] & 0xF0;
                if(!(ctx && ctx.bRO===true))
                {
                    rtc.ram[0x0C] = 0x00;
                    rtcClearInterrupt();
                }
                return flags;
            }

            case 0x0D:
                return 0x80;                                // valid time/RAM
        }

        // $0E-$3F are battery-backed RAM and are not affected by RTC updates.
        return rtc.ram[reg] & 0xFF;
    }

    function rtcWriteData(value)
    {
        var reg = rtc.address & 0x3F;
        value &= 0xFF;

        if(reg==0x01 || reg==0x03 || reg==0x05)
        {
            rtc.ram[reg] = value;                           // alarm registers
            return;
        }

        if(reg==0x0A)
        {
            rtc.ram[0x0A] = value & 0x7F;                  // UIP is read only
            return;
        }

        if(reg==0x0B)
        {
            var wasHeld = (rtc.ram[0x0B] & 0x80) != 0;
            var willHold = (value & 0x80) != 0;

            // Freeze the exact current emulated clock before asserting SET.
            if(!wasHeld && willHold)
                rtcRebase(rtcCurrentDate());

            rtc.ram[0x0B] = value;

            // Clearing SET restarts elapsed-time accumulation from the frozen
            // value rather than jumping by the amount of time spent halted.
            if(wasHeld && !willHold)
            {
                rtc.hostBaseMs = Date.now();
                rtc.lastUpdateSecond = Math.floor(rtc.baseTimeMs/1000);
            }
            return;
        }

        if(reg==0x0C || reg==0x0D)
            return;                                         // read-only registers

        if(reg>=0x0E)
        {
            rtc.ram[reg] = value;                           // battery RAM

            // The ROM control panel stores the saved 6551 configuration in
            // battery RAM $23/$24.  Defer DOM work to the dashboard refresh
            // sequencer; merely flag that the configured SER controls changed.
            if(serialUI && (reg==0x23 || reg==0x24))
                serialUI.configDirty = true;            
            return;
        }

        var date = rtcCurrentDate();
        var decoded = rtcDecode(value);

        switch(reg)
        {
            case 0x00:
                date.setSeconds(Math.max(0,Math.min(59,decoded)),0);
                break;
            case 0x02:
                date.setMinutes(Math.max(0,Math.min(59,decoded)));
                break;
            case 0x04:
                date.setHours(rtcDecodeHour(value));
                break;
            case 0x06:
            {
                // The DOW counter is independently writable on the 6818.  Keep
                // an offset from JavaScript's calendar weekday so it advances
                // naturally while still honoring a value explicitly written.
                var requested = Math.max(1,Math.min(7,decoded));
                var actual = date.getDay()+1;
                rtc.weekdayOffset = (requested - actual + 7) % 7;
                return;
            }
            case 0x07:
                date.setDate(Math.max(1,Math.min(31,decoded)));
                break;
            case 0x08:
                date.setMonth(Math.max(1,Math.min(12,decoded))-1);
                break;
            case 0x09:
            {
                var year = Math.max(0,Math.min(99,decoded));
                var century = Math.floor(date.getFullYear()/100)*100;
                date.setFullYear(century + year);
                break;
            }
        }

        rtcRebase(date);
    }

    this.readSlotIO = function(addr,ctx)
    {
        addr &= 0x0F;

        if(addr>=0x08 && addr<=0x0B)
            aciaSyncNow(ctx);

        switch(addr)
        {
            case 0x05:      // $C085+$s0: selected 6818 Clock/RAM data
                return rtcReadData(ctx);
            case 0x08:      // $C088+$s0: 6551 Receiver Data Register
                return aciaReadData(ctx);

            case 0x09:      // $C089+$s0: 6551 Status Register
                return aciaReadStatus(ctx);

            case 0x0A:      // $C08A+$s0: 6551 Command Register
                return acia.command & 0xFF;

            case 0x0B:      // $C08B+$s0: 6551 Control Register
                return acia.control & 0xFF;
        }

        // $x4, $x6 and $x7 are write-only.
        return 0x00;
    };

    this.readROM = function(addr,ctx)
    {
        /*
         * $Cn00-$CnFF slot-page view.
         *
         * The 27C64 does not contain one generic SlotROM.  Its final seven
         * 256-byte pages are pre-assembled for slots 1..7:
         *
         *     slot 1 -> EPROM $1900
         *     slot 2 -> EPROM $1A00
         *       ...
         *     slot 7 -> EPROM $1F00
         *
         * Therefore a live card moved to another slot automatically exposes
         * the authentic slot-specific bytes; no run-time patching is needed.
         */
        selectExpansionROM(ctx);

        addr &= 0xFF;
        if(!serialpro.mount) return 0xFF;

        /*
         * RetroAppleJS stores peripheral slots with an internal +1 offset:
         *   Apple slot 2 -> mount.slotN == 3
         * (slotID2n()/slot2ID() in EMU_apple2io.js).
         * Convert back to the real Apple slot number before selecting the
         * corresponding pre-assembled SlotROM page in the 27C64.
         */
        var slotN = Number(serialpro.mount.slotN) - 1;
        if(!Number.isInteger(slotN) || slotN<1 || slotN>7) return 0xFF;

        var eprom_addr = 0x1800 + (slotN << 8) + addr;
        return SERIALPRO_EPROM[eprom_addr] & 0xFF;
    };


    this.writeSlotIO = function(addr,d8,ctx)
    {
        /*
         * AE Serial Pro Programmer's Reference register map:
         *
         *   $C084+$s0  6818 Clock/RAM Address       (write only)
         *   $C085+$s0  6818 Clock/RAM Data          (read/write)
         *   $C086+$s0  EPROM Bank Register Clear    (write only)
         *   $C087+$s0  EPROM Bank Register          (write only)
         *   $C088+$s0  6551 Data                    (read/write)
         *   $C089+$s0  6551 Status / Program Reset  (read/write)
         *   $C08A+$s0  6551 Command                 (read/write)
         *   $C08B+$s0  6551 Control                 (read/write)
         *
         * Apple2IO passes SlotIO as an offset $0..$F within the mounted slot's
         * $C0s0-$C0sF range, hence BANKCLR/BANKREG are offsets $06/$07.
         *
         * IMPORTANT: this register is independent of C8 ownership.  A bank write
         * changes which EPROM bytes back logical $C800-$CFFF immediately, even
         * while the CPU is executing there.  It does not itself claim or release
         * the Apple II expansion-ROM window.
         */
        addr &= 0x0F;
        d8 &= 0xFF;

        if(addr>=0x08 && addr<=0x0B)
            aciaSyncNow(ctx);

        switch(addr)
        {
            case 0x04:      // $C084+$s0: 6818 Clock/RAM address register
                rtc.address = d8 & 0x3F;
                return 0x00;

            case 0x05:      // $C085+$s0: selected 6818 Clock/RAM data
                rtcWriteData(d8);
                return 0x00;            
            case 0x06:      // $C086+$s0: EPROM Bank Register Clear
                // The hardware operation is selected by the address; the byte
                // written is irrelevant.  Return to the resident HostROM bank 0.
                state.romSelector = 0x00;
                if(bDebug) console.log("Serial Pro EPROM BANKCLR -> selector $00");
                return 0x00;

            case 0x07:      // $C087+$s0: EPROM Bank Register
                // Retain the whole selector.  Only bits 0-1 are used to choose
                // the physical 2 KiB quarter; higher bits are decoded by firmware.
                state.romSelector = d8;
                if(bDebug)
                    console.log(
                        "Serial Pro EPROM BANKREG <- $"+d8.toString(16).padStart(2,"0")+
                        " (physical bank "+physicalHostROMBank()+")"
                    );
                return 0x00;
            case 0x08:      // $C088+$s0: 6551 Transmitter Data Register
                aciaWriteData(d8);
                return 0x00;

            case 0x09:      // $C089+$s0: 6551 programmed reset; d8 is don't-care
                aciaProgramReset();
                return 0x00;

            case 0x0A:      // $C08A+$s0: 6551 Command Register
                aciaWriteCommand(d8);
                return 0x00;

            case 0x0B:      // $C08B+$s0: 6551 Control Register
                aciaWriteControl(d8);
                return 0x00;
        }
        return 0x00;
    };


    this.readHostROM = function(addr,ctx)
    {
        /*
         * $C800-$CFFF shared expansion-ROM view.
         *
         * The CPU-visible address selects one byte within a 2 KiB window, while
         * the Serial Pro EPROM selector chooses which physical 27C64 quarter is
         * behind that window:
         *
         *     EPROM = ((romSelector & $03) * $0800) + (CPU - $C800)
         *
         * This lookup is performed on every fetch.  Consequently a firmware
         * instruction such as STA $C087,Y can switch banks and the very next
         * opcode fetched at the same logical $C8xx address comes from the newly
         * selected physical bank, matching the observed AE firmware design.
         */
        var rel_addr;

        if(ctx && Number.isFinite(ctx.rel_addr))
            rel_addr = ctx.rel_addr;
        else if(ctx && Number.isFinite(ctx.line))
            rel_addr = ctx.line + (addr & 0xFF);
        else
            rel_addr = (serialpro.action.HostROM.base || 0x800) + (addr & 0xFF);

        if(!ownsExpansionROM()) return 0x00;
        var bank_addr = rel_addr - 0x800;
        var eprom_addr = (physicalHostROMBank() << 11) + bank_addr;
        var d8 = bank_addr>=0 && bank_addr<0x800
            ? SERIALPRO_EPROM[eprom_addr]
            : 0x00;

        // $CFFF releases C8 ownership only.  It does NOT clear the AE bank
        // register; BANKCLR at $C086+$s0 is a separate hardware operation.
        if((rel_addr & 0x0FFF)==0x0FFF && !(ctx && ctx.bRO===true))
            releaseExpansionROM();

        return d8 & 0xFF;
    };

