        serialUISetChecked(controlID,"serial_cpu_sync",state.cpuSync);
        serialUISetChecked(controlID,"physical_dtr",aciaDTRAsserted());
        serialUISetChecked(controlID,"physical_rts",aciaRTSAsserted());

